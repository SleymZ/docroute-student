import type { OfficialSource, StudyIntake } from "@/types/admission";
import type { PendingProgramGroup, ReferenceRules } from "@/data/pending-programs";

// European universities beyond Slovakia, Czechia, Austria and Germany's
// first listings (PR #29, checked 2026-10-29 on each university's own
// site). All are "coming soon": reference rules only, no matching, no
// checklist, no residence route for these countries. Tuition is quoted for
// non-EU citizens because a non-EU citizen with Slovak residence usually
// pays the non-EU rate; the university confirms the fee status.

const checked = "2026-10-29";
const rechecked = "2026-10-30";

function source(id: string, title: string, publisher: string, url: string, at = checked): OfficialSource {
  return { id, title, publisher, url, checkedAt: at };
}

type GroupInput = Omit<PendingProgramGroup, "intake" | "checkedAt" | "referenceRules"> & {
  referenceRules: Omit<ReferenceRules, "checkedAt">;
};

function group(input: GroupInput, at = checked): PendingProgramGroup {
  return {
    ...input,
    intake: "2027/28" as StudyIntake,
    checkedAt: at,
    referenceRules: { ...input.referenceRules, checkedAt: at },
  };
}

